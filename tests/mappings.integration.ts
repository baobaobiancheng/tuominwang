import { test, after } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import pg from "pg";
import { buildApp } from "../apps/api/main.ts";
import { tick } from "../apps/worker/main.ts";
import { pool, scoped, rows, sql } from "../packages/adapters/db.ts";
import { passwordHash } from "../packages/adapters/storage.ts";

const admin = new pg.Pool({ connectionString: process.env.MIGRATION_DATABASE_URL }), app = await buildApp();
after(async () => { await app.close(); await pool.end(); await admin.end(); });
test("immutable encrypted aliases require explicit reuse, bind versions and isolate restoration from other projects/users", async () => {
  const origin = process.env.APP_ORIGIN!, tenant = randomUUID(), uid = randomUUID(), password = "synthetic-mapping-password";
  async function account(user: string) {
    const username = "mapping-" + randomUUID();
    await admin.query("INSERT INTO users VALUES($1,$2,$3,$4)", [user, tenant, username, passwordHash(password)]);
    const login = await app.inject({ method: "POST", url: "/api/login", headers: { origin }, payload: { username, password } });
    const cookie = String(login.headers["set-cookie"]).split(";")[0];
    return (method: any, url: string, payload?: any) => app.inject({ method, url, headers: { origin, cookie }, payload });
  }
  const req = await account(uid), other = await account(randomUUID());
  const project = (await req("POST", "/api/projects", { name: "实体假名" })).json().id;
  const doc = (await req("POST", `/api/projects/${project}/documents`, { text: "甲乙公司与甲乙公司", requestId: randomUUID() })).json().id;
  await tick();
  const span = { revision: 0, start: 0, end: 4, kind: "机构" }, requestId = randomUUID();
  assert.deepEqual((await req("POST", `/api/documents/${doc}/mapping-proposals`, span)).json().proposals, []);
  const ref = (await req("POST", `/api/documents/${doc}/mappings`, { ...span, requestId })).json();
  assert.equal(ref.token, "【机构_000001】");
  assert.deepEqual((await req("POST", `/api/documents/${doc}/mappings`, { ...span, requestId })).json(), ref);
  assert.equal((await req("POST", `/api/documents/${doc}/mappings`, { ...span, end: 2, requestId })).json().error, "IDEMPOTENCY_CONFLICT");
  const secondSpan = { ...span, start: 5, end: 9 };
  assert.deepEqual((await req("POST", `/api/documents/${doc}/mapping-proposals`, secondSpan)).json().proposals, [ref]);
  const independent = (await req("POST", `/api/documents/${doc}/mappings`, { ...secondSpan, requestId: randomUUID() })).json();
  assert.notEqual(independent.mappingId, ref.mappingId);
  assert.equal(independent.token, "【机构_000002】");
  const stored = (await admin.query("SELECT payload FROM entity_mappings WHERE project_id=$1", [project])).rows;
  assert.ok(stored.every(r => !r.payload.includes("甲乙公司")));
  await assert.rejects(scoped(uid, tenant, db => rows(db, sql`UPDATE entity_mappings SET token='tampered' WHERE id=${ref.mappingId}`)), (error: any) => error.cause?.code === "42501");
  assert.equal((await other("GET", `/api/projects/${project}/mappings`)).statusCode, 404);
  assert.equal((await other("POST", `/api/documents/${doc}/mapping-proposals`, span)).statusCode, 404);
  const marks = [span, secondSpan].map(({ revision: _, ...m }) => ({ ...m, decision: "redact", replacement: ref }));
  assert.equal((await req("PUT", `/api/documents/${doc}/review`, { revision: 0, marks: [{ ...marks[0], replacement: { ...ref, token: "【机构_000003】" } }] })).json().error, "MAPPING_MISMATCH");
  assert.equal((await req("PUT", `/api/documents/${doc}/review`, { revision: 0, marks })).statusCode, 200);
  assert.equal((await req("POST", `/api/documents/${doc}/export`, { revision: 1 })).statusCode, 200); await tick();
  const link = (await req("POST", `/api/documents/${doc}/download-link`, { revision: 1 })).json();
  const output = (await app.inject({ url: link.url })).body;
  assert.equal(output, `${ref.token}与${ref.token}`);
  assert.equal((await req("POST", `/api/documents/${doc}/restore`, { revision: 1, text: output })).json().text, "甲乙公司与甲乙公司");
  assert.equal((await req("POST", `/api/documents/${doc}/restore`, { revision: 1, text: independent.token })).json().error, "UNKNOWN_ALIAS");
  assert.equal((await other("POST", `/api/documents/${doc}/restore`, { revision: 1, text: output })).statusCode, 404);
  const secondProject = (await req("POST", "/api/projects", { name: "隔离项目" })).json().id;
  const secondDoc = (await req("POST", `/api/projects/${secondProject}/documents`, { text: "甲乙公司", requestId: randomUUID() })).json().id; await tick();
  assert.equal((await req("PUT", `/api/documents/${secondDoc}/review`, { revision: 0, marks: [marks[0]] })).json().error, "MAPPING_MISMATCH");
  assert.equal((await req("PUT", `/api/documents/${doc}/review`, { revision: 1, marks })).statusCode, 200);
  assert.equal((await req("POST", `/api/documents/${doc}/restore`, { revision: 1, text: output })).statusCode, 409);
  assert.equal((await app.inject({ url: link.url })).statusCode, 200);
  const audit = (await admin.query("SELECT event FROM audit WHERE project_id=$1", [project])).rows.map(r => r.event);
  assert.ok(audit.includes("mapping_created")); assert.ok(audit.includes("text_restored"));
});
test("project review is atomic on invalid spans and stale versions; explicit undo creates new immutable snapshots", async () => {
  const origin = process.env.APP_ORIGIN!, tenant = randomUUID(), uid = randomUUID(), password = "synthetic-batch-password", username = "batch-" + randomUUID();
  await admin.query("INSERT INTO users VALUES($1,$2,$3,$4)", [uid, tenant, username, passwordHash(password)]);
  const login = await app.inject({ method: "POST", url: "/api/login", headers: { origin }, payload: { username, password } });
  const cookie = String(login.headers["set-cookie"]).split(";")[0];
  const req = (method: any, url: string, payload?: any) => app.inject({ method, url, headers: { origin, cookie }, payload });
  const project = (await req("POST", "/api/projects", { name: "整批一致性" })).json().id;
  const ids: string[] = [];
  for (let i = 0; i < 2; i++) { ids.push((await req("POST", `/api/projects/${project}/documents`, { text: "13800138000", requestId: randomUUID() })).json().id); await tick(); }
  ids.sort();
  const first = (await req("GET", `/api/documents/${ids[0]}`)).json(), second = (await req("GET", `/api/documents/${ids[1]}`)).json();
  const overlapping = [...second.marks, { start: 0, end: 5, kind: "自定义", decision: "pending" }];
  assert.equal((await req("PUT", `/api/documents/${ids[1]}/review`, { revision: 0, marks: overlapping })).statusCode, 200);
  let documents = [{ id: ids[0], revision: 0 }, { id: ids[1], revision: 1 }];
  assert.equal((await req("POST", `/api/projects/${project}/review-batch/apply`, { documents })).json().error, "OVERLAPPING_MARKS");
  assert.equal((await req("GET", `/api/documents/${ids[0]}`)).json().revision, 0);
  assert.equal((await admin.query("SELECT COUNT(*)::int AS n FROM review_snapshots WHERE document_id=$1", [ids[0]])).rows[0].n, 1);
  assert.equal((await req("PUT", `/api/documents/${ids[1]}/review`, { revision: 1, marks: second.marks })).statusCode, 200);
  assert.equal((await req("POST", `/api/projects/${project}/review-batch/apply`, { documents })).statusCode, 409);
  documents = [{ id: ids[0], revision: 0 }, { id: ids[1], revision: 2 }];
  const preview = await req("POST", `/api/projects/${project}/review-batch/preview`, { documents });
  assert.equal(preview.statusCode, 200); assert.deepEqual(preview.json().documents.map((d: any) => d.affected), [1, 1]);
  assert.equal((await req("GET", `/api/documents/${ids[0]}`)).json().revision, 0);
  const applied = await req("POST", `/api/projects/${project}/review-batch/apply`, { documents });
  assert.equal(applied.statusCode, 200);
  assert.equal((await req("GET", `/api/documents/${ids[0]}`)).json().marks[0].decision, "redact");
  const receipt = applied.json().documents;
  assert.equal((await req("POST", `/api/projects/${project}/review-batch/undo`, { documents: receipt })).statusCode, 200);
  const undone = (await req("GET", `/api/documents/${ids[0]}`)).json();
  assert.equal(undone.revision, 2); assert.deepEqual(undone.marks, first.marks);
  assert.equal((await req("POST", `/api/projects/${project}/review-batch/undo`, { documents: receipt })).statusCode, 409);
  const otherProject = (await req("POST", "/api/projects", { name: "其他项目" })).json().id;
  assert.equal((await req("POST", `/api/projects/${otherProject}/review-batch/apply`, { documents: [{ id: ids[0], revision: 2 }] })).statusCode, 404);
});
