test('Word-scope batch export mode preserves both reviewed drafts atomically',{timeout:120000},async()=>{
  const startedAt=Date.now();const milestone=(stage:string)=>console.log('FULL_STAR_STAGE '+JSON.stringify({stage,elapsedMs:Date.now()-startedAt}));
  const tenant=randomUUID(),user=randomUUID(),password='synthetic-batch-export-mode',username='batch-mode-'+user,origin=process.env.APP_ORIGIN!;
  await admin.query('INSERT INTO users VALUES($1,$2,$3,$4)',[user,tenant,username,passwordHash(password)]);
  const login=await app.inject({method:'POST',url:'/api/login',headers:{origin},payload:{username,password}});
  assert.equal(login.statusCode,200,login.body);
  const cookie=String(login.headers['set-cookie']).split(';')[0];
  const req=(method:'GET'|'POST'|'PUT',url:string,payload?:any,binary=false)=>app.inject({method,url,payload,headers:{origin,cookie,...binary?{'content-type':'application/octet-stream'}:{}}});
  const made=await req('POST','/api/projects',{name:'synthetic two Word batch mode'});
  assert.equal(made.statusCode,200,made.body);
  const project=made.json().id as string;
  const bytes=await officeFixture('docx');
  const batch=randomUUID(),entries=[1,2].map(n=>({requestId:randomUUID(),path:`batch-${n}.docx`,size:bytes.length}));
  const accepted=await req('POST',`/api/projects/${project}/upload-batches`,{id:batch,files:entries});
  assert.equal(accepted.statusCode,200,accepted.body);
  const ids:string[]=[];
  for(const e of entries){
    const uploaded=await req('POST',`/api/projects/${project}/files?batchId=${batch}&requestId=${e.requestId}`,bytes,true);
    assert.equal(uploaded.statusCode,200,uploaded.body);
    ids.push(uploaded.json().id);
  }
  for(let i=0;i<4;i++){
    const views=await Promise.all(ids.map(id=>req('GET',`/api/documents/${id}`)));
    if(views.every(v=>v.statusCode===200&&v.json().state==='review'))break;
    assert.equal(await tick(),true,'queued synthetic DOCX should be processed');
  }
  const initial=await Promise.all(ids.map(async id=>{
    const response=await req('GET',`/api/documents/${id}`);
    assert.equal(response.statusCode,200,response.body);
    const view=response.json();assert.equal(view.state,'review',response.body);
    const mode=await req('GET',`/api/documents/${id}/configuration`);
    assert.equal(mode.statusCode,200,mode.body);
    const source=(await admin.query('SELECT source_id FROM documents WHERE id=$1',[id])).rows[0];
    assert.deepEqual(await readOriginal(source.source_id),bytes);
    return {view,mode:mode.json().effective.profile.mode};
  }));
  assert.equal(new Set(initial.map(x=>x.mode)).size,1);
  const named=await req('POST',`/api/documents/${ids[0]}/configuration`,{revision:initial[0].view.revision,configuration:{pseudonymTableName:'保留的逐材料表名'}});
  assert.equal(named.statusCode,200,named.body);
  const recognize=await req('POST',`/api/documents/${ids[0]}/recognize`,{revision:named.json().revision,ner:false});
  assert.equal(recognize.statusCode,200,recognize.body);
  assert.equal(await tick(),true,'named policy re-recognition should finish');
  const namedReview=await req('GET',`/api/documents/${ids[0]}`);
  assert.equal(namedReview.statusCode,200,namedReview.body);
  assert.equal(namedReview.json().state,'review',namedReview.body);
  initial[0].view=namedReview.json();
  const reviewed=await Promise.all(ids.map(async(id,index)=>{
    const view=initial[index].view,marks=view.marks.map((m:any,i:number)=>({...m,decision:i<2?'redact':'ignore',...i===0?{replacement:{mode:'custom',value:'SYNTHETIC_ALIAS'},replacementOrigin:'manual'}:{}}));
    const saved=await req('PUT',`/api/documents/${id}/review`,{revision:view.revision,marks});
    assert.equal(saved.statusCode,200,saved.body);
    return {revision:saved.json().revision,marks};
  }));
  const beforeExport=await req('POST',`/api/documents/${ids[0]}/export`,{revision:reviewed[0].revision});
  assert.equal(beforeExport.statusCode,200,beforeExport.body);
  assert.equal(await tick(),true);
  const beforeLink=await req('POST',`/api/documents/${ids[0]}/download-link`,{revision:reviewed[0].revision});
  assert.equal(beforeLink.statusCode,200,beforeLink.body);
  const beforeBytes=await app.inject({url:beforeLink.json().url});
  assert.equal(beforeBytes.statusCode,200,beforeBytes.body);
  // One atomic operation matches the original renderer's selected-Word action.
  const changed=await req('POST',`/api/projects/${project}/review-mode-batch/apply`,{
    documents:ids.map((id,index)=>({id,revision:reviewed[index].revision})),
    scope:'docx',mode:'full_star',confirmOverride:true,
  });
  assert.equal(changed.statusCode,200,changed.body);
  milestone('batch-applied');
  const after=await Promise.all(ids.map(async id=>{
    const doc=await req('GET',`/api/documents/${id}`),mode=await req('GET',`/api/documents/${id}/configuration`);
    assert.equal(doc.statusCode,200,doc.body);assert.equal(mode.statusCode,200,mode.body);
    return {state:doc.json().state,revision:doc.json().revision,marks:doc.json().marks,mode:mode.json().effective.profile.mode,tableName:mode.json().configuration.pseudonymTableName};
  }));
  console.log('BATCH_MODE_BATCH_CONTRACT_OBSERVATION '+JSON.stringify({before:initial.map(x=>({state:x.view.state,revision:x.view.revision,mode:x.mode})),reviewed:reviewed.map(x=>({revision:x.revision,markCount:x.marks.length})),after:after.map(x=>({state:x.state,revision:x.revision,mode:x.mode,markCount:x.marks.length}))}));
  assert.deepEqual(after.map(x=>x.mode),['full_star','full_star'],'one Word-scope action should apply to both selected DOCX');
  assert.deepEqual(after.map(x=>x.state),['review','review'],'mode change should preserve reviewed drafts without re-recognition');
  assert.deepEqual(after.map(x=>x.marks.map((m:any)=>({start:m.start,end:m.end,kind:m.kind,decision:m.decision,sources:m.sources}))),reviewed.map(x=>x.marks.map((m:any)=>({start:m.start,end:m.end,kind:m.kind,decision:m.decision,sources:m.sources}))),'all source spans, identities and review decisions should remain intact');
  assert.deepEqual(after.map(x=>x.marks[0].replacement),[{mode:'custom',value:'SYNTHETIC_ALIAS'},{mode:'custom',value:'SYNTHETIC_ALIAS'}]);
  assert.deepEqual(after.map(x=>x.marks[1].replacement?.mode),['full','full'],'policy-origin marks must change to full masking');
  assert.deepEqual(after.map(x=>x.tableName),['保留的逐材料表名',undefined]);
  const originalText=unseal((await admin.query('SELECT content FROM documents WHERE id=$1',[ids[0]])).rows[0].content,`${tenant}:${project}:${ids[0]}`);
  const firstValue=originalText.slice(reviewed[0].marks[0].start,reviewed[0].marks[0].end),firstStars='*'.repeat([...firstValue].length);
  assert.ok(firstValue&&originalText.split(firstValue).length===2,'the first reviewed source value is unique in the synthetic Word document');
  const fullPreview=await req('POST',`/api/documents/${ids[0]}/preview`,{revision:after[0].revision,marks:after[0].marks,offset:after[0].marks[0].start});
  milestone('full-preview-response');
  assert.equal(fullPreview.statusCode,200,fullPreview.body);
  assert.ok(fullPreview.json().text.includes(firstStars),'processing preview shows original rr2 stars for the first reviewed source');
  assert.ok(!fullPreview.json().text.includes(firstValue)&&!fullPreview.json().text.includes('SYNTHETIC_ALIAS'),'processing preview hides the first source and stored manual draft');
  const oldSigned=await app.inject({url:beforeLink.json().url});
  assert.equal(oldSigned.statusCode,200,oldSigned.body);
  assert.deepEqual(oldSigned.rawPayload,beforeBytes.rawPayload,'previously issued artifact keeps its original bytes');
  const afterExport=await req('POST',`/api/documents/${ids[0]}/export`,{revision:after[0].revision});
  milestone('full-export-queued');
  assert.equal(afterExport.statusCode,200,afterExport.body);
  assert.equal(await tick(),true);
  const afterLink=await req('POST',`/api/documents/${ids[0]}/download-link`,{revision:after[0].revision});
  assert.equal(afterLink.statusCode,200,afterLink.body);
  const afterBytes=await app.inject({url:afterLink.json().url});
  assert.equal(afterBytes.statusCode,200,afterBytes.body);
  const secondOriginal=originalText.slice(reviewed[0].marks[1].start,reviewed[0].marks[1].end);
  const beforeText=(await parseOffice(beforeBytes.rawPayload,'docx')).text,afterText=(await parseOffice(afterBytes.rawPayload,'docx')).text;
  assert.ok(beforeText.includes('SYNTHETIC_ALIAS'),'prior effective output retains the manual draft');
  assert.ok(!afterText.includes('SYNTHETIC_ALIAS'),'full-star effective output must override the stored manual draft');
  assert.ok(!afterText.includes(firstValue),'new full-star output removes the unique first source value');
  assert.ok(afterText.includes(firstStars),'full-star output follows original rr2 Unicode code-point length');
  assert.ok(!afterText.includes(secondOriginal),'new full-star export must remove the second source value');
  assert.notEqual(afterText,beforeText,'actual downloaded output must change with the batch mode');
  const stale=await req('POST',`/api/projects/${project}/review-mode-batch/apply`,{documents:ids.map((id,index)=>({id,revision:reviewed[index].revision})),scope:'docx',mode:'default_star',confirmOverride:true});
  assert.equal(stale.statusCode,409,stale.body);
  const foreignProject=(await req('POST','/api/projects',{name:'synthetic foreign batch target'})).json().id;
  const crossProject=await req('POST',`/api/projects/${foreignProject}/review-mode-batch/apply`,{documents:ids.map((id,index)=>({id,revision:after[index].revision})),scope:'docx',mode:'default_star',confirmOverride:true});
  assert.equal(crossProject.statusCode,404,crossProject.body);
  const outsider=randomUUID(),outsiderTenant=randomUUID(),outsiderPassword='synthetic-outsider-password',outsiderName='batch-outsider-'+outsider;
  await admin.query('INSERT INTO users VALUES($1,$2,$3,$4)',[outsider,outsiderTenant,outsiderName,passwordHash(outsiderPassword)]);
  const outsiderLogin=await app.inject({method:'POST',url:'/api/login',headers:{origin},payload:{username:outsiderName,password:outsiderPassword}});
  assert.equal(outsiderLogin.statusCode,200,outsiderLogin.body);
  const outsiderCookie=String(outsiderLogin.headers['set-cookie']).split(';')[0];
  const forbidden=await app.inject({method:'POST',url:`/api/projects/${project}/review-mode-batch/apply`,headers:{origin,cookie:outsiderCookie},payload:{documents:ids.map((id,index)=>({id,revision:after[index].revision})),scope:'docx',mode:'default_star',confirmOverride:true}});
  assert.ok([403,404].includes(forbidden.statusCode),forbidden.body);
  for(let i=0;i<ids.length;i++){const read=await req('GET',`/api/documents/${ids[i]}`);assert.equal(read.json().revision,after[i].revision);assert.deepEqual(read.json().marks,after[i].marks);}
  const sameMode=await req('POST',`/api/projects/${project}/review-mode-batch/apply`,{documents:ids.map((id,index)=>({id,revision:after[index].revision})),scope:'docx',mode:'full_star'});
  assert.equal(sameMode.statusCode,200,sameMode.body);
  assert.deepEqual(sameMode.json().documents.map((entry:any)=>entry.status),['unchanged','unchanged']);
  for(let i=0;i<ids.length;i++){const read=await req('GET',`/api/documents/${ids[i]}`);assert.equal(read.json().revision,after[i].revision+1);assert.deepEqual(read.json().marks,after[i].marks);}
  const aliasMode=await req('POST',`/api/projects/${project}/review-mode-batch/apply`,{documents:ids.map((id,index)=>({id,revision:after[index].revision+1})),scope:'docx',mode:'custom_pseudonym',confirmOverride:true});
  assert.equal(aliasMode.statusCode,200,aliasMode.body);
  const aliased=(await req('GET',`/api/documents/${ids[0]}`)).json();
  assert.equal(aliased.revision,after[0].revision+2);
  assert.deepEqual(aliased.marks[0].replacement,{mode:'custom',value:'SYNTHETIC_ALIAS'});
  assert.equal(aliased.marks[1].replacement.mode,'alias');
  const aliasToken=aliased.marks[1].replacement.token as string;
  assert.ok(aliasToken.startsWith('【'));
  const aliasExport=await req('POST',`/api/documents/${ids[0]}/export`,{revision:aliased.revision});assert.equal(aliasExport.statusCode,200,aliasExport.body);assert.equal(await tick(),true);
  const aliasLink=await req('POST',`/api/documents/${ids[0]}/download-link`,{revision:aliased.revision});assert.equal(aliasLink.statusCode,200,aliasLink.body);
  const aliasBytes=await app.inject({url:aliasLink.json().url});assert.equal(aliasBytes.statusCode,200,aliasBytes.body);
  const aliasText=(await parseOffice(aliasBytes.rawPayload,'docx')).text;
  assert.ok(aliasText.includes(aliasToken)&&aliasText.includes('SYNTHETIC_ALIAS'),'real alias download must keep generated token and manual value');
  const partial=await req('POST',`/api/projects/${project}/review-mode-batch/apply`,{documents:ids.map((id,index)=>({id,revision:after[index].revision+2})),scope:'docx',mode:'default_star',confirmOverride:true});
  assert.equal(partial.statusCode,200,partial.body);
  const partialView=(await req('GET',`/api/documents/${ids[0]}`)).json();
  assert.equal(partialView.marks[1].replacement.mode,'reference-mask');
  assert.deepEqual(partialView.marks[0].replacement,{mode:'custom',value:'SYNTHETIC_ALIAS'});
  const partialExport=await req('POST',`/api/documents/${ids[0]}/export`,{revision:partialView.revision});assert.equal(partialExport.statusCode,200,partialExport.body);assert.equal(await tick(),true);
  const partialLink=await req('POST',`/api/documents/${ids[0]}/download-link`,{revision:partialView.revision});assert.equal(partialLink.statusCode,200,partialLink.body);
  const partialBytes=await app.inject({url:partialLink.json().url});assert.equal(partialBytes.statusCode,200,partialBytes.body);
  const partialText=(await parseOffice(partialBytes.rawPayload,'docx')).text;
  assert.ok(!partialText.includes(aliasToken)&&partialText.includes('SYNTHETIC_ALIAS'));
  assert.notEqual(partialText,aliasText);
});

