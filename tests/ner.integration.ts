import { test, after } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import pg from "pg";
import { buildApp } from "../apps/api/main.ts";
import { tick } from "../apps/worker/main.ts";
import { pool } from "../packages/adapters/db.ts";
import { passwordHash } from "../packages/adapters/storage.ts";

process.env.NER_ENABLED = "1";
const admin = new pg.Pool({ connectionString: process.env.MIGRATION_DATABASE_URL });
const app = await buildApp();
after(async () => { await app.close(); await pool.end(); await admin.end(); });
test("real Chinese NER job preserves original offsets, immutable runs and review-to-download flow", async () => {
  const user = randomUUID(), tenant = randomUUID(), username = "ner-" + randomUUID(), password = "synthetic-ner-test-password";
  await admin.query("INSERT INTO users VALUES($1,$2,$3,$4)", [user, tenant, username, passwordHash(password)]);
  const origin = process.env.APP_ORIGIN!;
  const login = await app.inject({ method: "POST", url: "/api/login", headers: { origin }, payload: { username, password } });
  const cookie = String(login.headers["set-cookie"]).split(";")[0];
  const req = (method: any, url: string, payload?: any) => app.inject({ method, url, headers: { origin, cookie }, payload });
  const project = (await req("POST", "/api/projects", { name: "本地实体识别" })).json().id;
  const text = "😀张三在北京工作，电话13800138000。";
  const doc = (await req("POST", `/api/projects/${project}/documents`, { text, requestId: randomUUID() })).json().id;
  await tick();
  assert.equal((await req("POST", `/api/documents/${doc}/recognize`, { revision: 0, ner: true })).statusCode, 200);
  await tick();
  const view = (await req("GET", `/api/documents/${doc}`)).json();
  assert.equal(view.job.status, "succeeded", JSON.stringify(view.job));
  assert.equal(view.layers.ner, "completed");
  assert.equal(view.text, text);
  assert.deepEqual(view.marks.map((m: any) => text.slice(m.start, m.end)), ["张三", "北京", "13800138000"]);
  assert.ok(view.marks[0].sources.some((s: any) => s.layer === "ner"));
  assert.equal(view.marks[0].start, 2);
  const snapshots = (await admin.query("SELECT recognition,revision FROM review_snapshots WHERE document_id=$1 ORDER BY revision", [doc])).rows;
  assert.equal(snapshots.length, 2);
  assert.equal(snapshots[0].recognition.ner, null);
  assert.match(snapshots[1].recognition.ner, /dc0de593/);
  assert.equal((await req("PUT", `/api/documents/${doc}/review`, { revision: 1, marks: view.marks.map((m: any) => ({ ...m, decision: "redact" })) })).statusCode, 200);
  assert.equal((await req("POST", `/api/documents/${doc}/export`, { revision: 2 })).statusCode, 200);
  await tick();
  const link = await req("POST", `/api/documents/${doc}/download-link`, { revision: 2 });
  assert.equal(link.statusCode, 200, link.body);
  const output = await app.inject({ url: link.json().url });
  assert.equal(output.statusCode, 200);
  assert.equal(output.body, "😀【姓名】在【地址】工作，电话【手机号】。");
});
