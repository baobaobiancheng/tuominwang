import { readFile } from "node:fs/promises";
import { test, expect } from "./fixture.ts";

test("desktop full-text search, bulk decisions, undo/redo and partial replacement preview lead to the real download", async ({ page }) => {
  await page.goto("/");
  await page.getByLabel("账号", { exact: true }).fill(process.env.E2E_USERNAME!);
  await page.getByLabel("密码", { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole("button", { name: "登录工作台" }).click();
  await page.locator("summary").click();
  await page.getByLabel("项目名称").fill("合成复核项目");
  await page.getByRole("button", { name: "新建项目", exact: true }).click();
  await page.getByRole("button", { name: "导入材料", exact: true }).click();
  await page.getByLabel("待处理文本").fill("客户甲13800138000；客户乙13900139000");
  await page.getByRole("button", { name: "提交并识别", exact: true }).click();
  await page.getByRole("button", { name: "逐条复核", exact: true }).click();
  await expect(page.getByLabel("标记 2 处理决定")).toBeVisible();
  await page.getByRole("button", { name: "全文查找", exact: true }).click();
  await page.getByLabel("全文查找", { exact: true }).fill("客户乙");
  await page.getByRole("button", { name: "查找", exact: true }).click();
  await page.getByLabel("查找结果", { exact: true }).locator("button.quote").click();
  await expect.poll(() => page.getByLabel("原文", { exact: true }).evaluate((el: HTMLTextAreaElement) => el.value.slice(el.selectionStart, el.selectionEnd))).toBe("客户乙");
  await page.getByRole("button", { name: "批量复核", exact: true }).click();
  await page.getByRole("button", { name: "批量脱敏", exact: true }).click();
  await expect(page.getByLabel("标记 2 处理决定")).toHaveValue("redact");
  await page.getByRole("button", { name: "撤销修改", exact: true }).click();
  await expect(page.getByLabel("标记 2 处理决定")).toHaveValue("pending");
  await expect(page.getByRole("button", { name: "保存复核", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "重做修改", exact: true }).click();
  await page.getByLabel("标记 1 脱敏方式").selectOption("mask");
  await page.getByLabel("标记 1 保留前几字").fill("3");
  await page.getByLabel("标记 1 保留后几字").fill("4");
  await page.getByLabel("标记 2 脱敏方式").selectOption("custom");
  await page.getByLabel("标记 2 替换文字").fill("联系号码");
  await page.getByRole("button", { name: "刷新处理预览", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "处理预览", exact: true })).toHaveValue("客户甲138***8000；客户乙联系号码");
  await page.screenshot({ path: "test-results/review-tools-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "保存复核", exact: true }).click();
  await expect(page.getByText("复核已保存", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "导出已选标记的处理副本", exact: true }).click();
  await expect(page.getByText("任务：已完成")).toBeVisible();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "核验并下载 TXT", exact: true }).click();
  const file = await (await download).path();
  expect(await readFile(file!, "utf8")).toBe("客户甲138***8000；客户乙联系号码");
  await expect(page.locator("body")).not.toContainText(/工程取舍|开发进度|第一批|第二批|浏览器验收/);
});

test("known-entity check locates the full document, invalidates changed drafts and adds reversible pending marks before verified export", async ({ page }) => {
  test.setTimeout(90000);
  await page.goto("/");
  await page.getByLabel("账号", { exact: true }).fill(process.env.E2E_USERNAME!);
  await page.getByLabel("密码", { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole("button", { name: "登录工作台" }).click();
  await page.locator("summary").click();
  await page.getByLabel("项目名称").fill("合成漏标检查项目");
  await page.getByRole("button", { name: "新建项目", exact: true }).click();
  await page.getByRole("button", { name: "导入材料", exact: true }).click();
  const text = "😀合成客户|" + "x".repeat(40000) + "|合成客户|合成客户";
  await page.getByLabel("待处理文本").fill(text);
  await page.getByRole("button", { name: "提交并识别", exact: true }).click();
  await expect(page.getByText("规则无命中，不代表没有敏感信息。可在原文中补充标记。", { exact: true })).toBeVisible({ timeout: 30000 });
  await page.getByRole("button", { name: "逐条复核", exact: true }).click();
  await page.getByLabel("原文", { exact: true }).evaluate((el: HTMLTextAreaElement) => { el.focus(); el.setSelectionRange(2, 6); el.dispatchEvent(new MouseEvent("mouseup", { bubbles: true })); });
  await page.getByRole("button", { name: "将选中文字加入标记", exact: true }).click();
  await page.getByLabel("标记 1 处理决定").selectOption("redact");
  await page.getByLabel("标记 1 脱敏方式").selectOption("custom");
  await page.getByLabel("标记 1 替换文字").fill("客户A");
  await page.getByRole("button", { name: "漏标检查", exact: true }).click();
  await page.getByRole("button", { name: "检查全文漏标", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "可补录 2 处" })).toBeVisible();
  await page.getByRole("table", { name: "全文漏标结果" }).getByRole("button", { name: "定位原文", exact: true }).click();
  await expect.poll(() => page.getByLabel("原文", { exact: true }).evaluate((el: HTMLTextAreaElement) => el.value.slice(el.selectionStart, el.selectionEnd))).toBe("合成客户");
  await page.getByRole("button", { name: "敏感标记", exact: true }).click();
  await page.getByLabel("标记 1 替换文字").fill("客户B");
  await expect(page.getByRole("table", { name: "全文漏标结果" })).toHaveCount(0);
  await page.getByRole("button", { name: "撤销修改", exact: true }).click();
  await expect(page.getByLabel("标记 1 替换文字")).toHaveValue("客户A");
  await expect(page.getByRole("table", { name: "全文漏标结果" })).toHaveCount(0);
  await page.getByRole("button", { name: "漏标检查", exact: true }).click();
  await page.getByRole("button", { name: "检查全文漏标", exact: true }).click();
  await page.getByRole("button", { name: "补录全部漏标到草稿", exact: true }).click();
  await expect(page.getByLabel("标记 2 处理决定")).toHaveValue("pending");
  await expect(page.getByLabel("标记 3 处理决定")).toHaveValue("pending");
  await expect(page.getByLabel("标记 2 替换文字")).toHaveCount(0);
  await page.getByRole("button", { name: "撤销修改", exact: true }).click();
  await expect(page.getByLabel("标记 3 处理决定")).toHaveCount(0);
  await page.getByRole("button", { name: "重做修改", exact: true }).click();
  await expect(page.getByLabel("标记 3 处理决定")).toHaveValue("pending");
  await page.getByRole("button", { name: "批量复核", exact: true }).click();
  await page.getByRole("button", { name: "批量脱敏", exact: true }).click();
  await expect(page.getByLabel("标记 2 处理决定")).toHaveValue("redact");
  await expect(page.getByLabel("标记 3 处理决定")).toHaveValue("redact");
  await expect(page.getByLabel("标记 2 替换文字")).toHaveValue("客户A");
  await expect(page.getByLabel("标记 3 替换文字")).toHaveValue("客户A");
  await page.getByRole("button", { name: "漏标检查", exact: true }).click();
  await page.getByRole("button", { name: "检查全文漏标", exact: true }).click();
  await expect(page.getByRole("table", { name: "全文漏标结果" })).toContainText("已完整标记");
  await page.screenshot({ path: "test-results/known-entity-check-desktop.png", fullPage: true });
  await page.getByRole("dialog", { name: "漏标检查", exact: true }).getByRole("button", { name: "返回敏感标记", exact: true }).click();
  await page.getByRole("button", { name: "保存复核", exact: true }).click();
  await expect(page.getByText("复核已保存", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "导出已选标记的处理副本", exact: true }).click();
  await expect(page.getByText("任务：已完成")).toBeVisible();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "核验并下载 TXT", exact: true }).click();
  const file = await (await download).path();
  expect(await readFile(file!, "utf8")).toBe("😀客户A|" + "x".repeat(40000) + "|客户A|客户A");
});
