test("desktop page regions, repeat across pages, deletion undo, pixel preview and PDF download", async ({ page }) => {
  test.setTimeout(90000);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/");
  await page.getByLabel("账号", { exact: true }).fill(process.env.E2E_USERNAME!);
  await page.getByLabel("密码", { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole("button", { name: "登录工作台" }).click();
  await page.locator(".create-project summary").click();
  await page.getByLabel("项目名称", { exact: true }).fill("区域处理-" + randomUUID().slice(0, 8));
  await page.getByRole("button", { name: "新建项目", exact: true }).click();
  await page.getByRole("button", { name: "导入材料", exact: true }).click();
  await page.getByLabel("选择文件", { exact: true }).setInputFiles({ name: "公开区域样本.pdf", mimeType: "application/pdf", buffer: pdfFixture({ pages: 2 }) });
  await page.getByRole("button", { name: "上传文件", exact: true }).click();
  await expect(page.getByText("已保存", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "返回材料列表", exact: true }).click();
  await page.getByRole("button", { name: /公开区域样本.pdf/ }).click();
  await page.getByRole("button", { name: "逐条复核", exact: true }).click();
  await expect(page.getByLabel("标记 2 处理决定")).toBeVisible({ timeout: 30000 });
  await page.getByLabel("标记 1 处理决定").selectOption("redact");
  await page.getByLabel("标记 2 处理决定").selectOption("redact");
  await expect(page.getByRole("button", { name: "导出已选标记的处理副本" })).toBeDisabled();
  const canvas = page.getByLabel("区域框选画布"); await canvas.scrollIntoViewIfNeeded();
  const rect = (await canvas.boundingBox())!;
  await page.mouse.move(rect.x + rect.width * .1, rect.y + rect.height * .3); await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * .3, rect.y + rect.height * .4); await page.mouse.up();
  await page.getByLabel("区域用途").selectOption("印章");
  await page.getByLabel("结束页", { exact: true }).fill("2");
  await page.getByRole("button", { name: "应用到指定页", exact: true }).click();
  await expect(page.getByText("印章 · 矩形区域 1", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "下一页原件", exact: true }).click();
  await expect(page.getByText("印章 · 矩形区域 1", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "从副本移除此页" }).click();
  await expect(page.getByText("此页不包含在副本中", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "撤销页面修改" }).click();
  await expect(page.getByText("此页不包含在副本中", { exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "从副本移除此页" }).click();
  await page.getByRole("button", { name: "上一页原件", exact: true }).click();
  await page.getByRole("checkbox", { name: "转换为不可选字的图片型 PDF 副本" }).check();
  await page.getByRole("button", { name: "查看本页处理预览", exact: true }).click();
  await expect(page.getByRole("img", { name: "处理预览第 1 页" })).toBeVisible();
  await page.screenshot({ path: "test-results/page-regions-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "保存复核", exact: true }).click();
  await expect(page.getByText("复核已保存", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "导出已选标记的处理副本", exact: true }).click();
  const button = page.getByRole("button", { name: "核验并下载 PDF", exact: true });
  await expect(button).toBeEnabled({ timeout: 30000 });
  const pendingDownload = page.waitForEvent("download"); await button.click(); const downloaded = await pendingDownload;
  // Keep PDFium/sharp in an ordinary short-lived process, outside Playwright's IPC worker.
  const inspected = JSON.parse(execFileSync(process.execPath,["--import","tsx","--input-type=module","--eval",`import{readFileSync}from'node:fs';import{openPdf}from'./packages/core/pdf-reader.ts';const pdf=await openPdf(readFileSync(0));try{console.log(JSON.stringify({count:pdf.count,meta:pdf.meta,text:(await pdf.page(0)).text}));}finally{pdf.close();}`],{input:await readFile((await downloaded.path())!),encoding:"utf8"}));
  expect(inspected).toEqual({count:1,meta:{},text:""});
  expect(await page.locator("body").innerText()).not.toMatch(/浏览器验收|工程评审|开发进度|技术取舍|完整一期/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test("DOCX embedded image review keeps document format and strips the original image resource", async ({ page }) => {
  test.setTimeout(90000);
  const jpeg = await readFile("tests/fixtures/office-image-public-synthetic.jpg");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/");
  await page.getByLabel("账号", { exact: true }).fill(process.env.E2E_USERNAME!);
  await page.getByLabel("密码", { exact: true }).fill(process.env.E2E_PASSWORD!);
  await page.getByRole("button", { name: "登录工作台" }).click();
  await page.locator(".create-project summary").click();
  await page.getByLabel("项目名称", { exact: true }).fill("内嵌图片-" + randomUUID().slice(0, 8));
  await page.getByRole("button", { name: "新建项目", exact: true }).click();
  await page.getByRole("button", { name: "导入材料", exact: true }).click();
  await page.getByLabel("选择文件", { exact: true }).setInputFiles({ name: "含图合同.docx", mimeType: "application/octet-stream", buffer: await officeImageFixture(jpeg) });
  await page.getByRole("button", { name: "上传文件", exact: true }).click();
  await expect(page.getByText("已保存", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "返回材料列表", exact: true }).click();
  await page.getByRole("button", { name: /含图合同.docx/ }).click();
  const image = page.getByRole("img", { name: "原件第 1 张图片" }); await expect(image).toBeVisible({ timeout: 30000 });
  await page.getByRole("button", { name: "逐条复核", exact: true }).click();
  const decisions = page.getByLabel(/^标记 \d+ 处理决定$/); expect(await decisions.count()).toBeGreaterThan(1);
  for (const decision of await decisions.all()) await decision.selectOption("redact");
  await expect(page.getByRole("button", { name: "核验并下载 DOCX", exact: true })).toBeVisible();
  await page.getByRole("checkbox", { name: "清除内嵌图片选区像素，生成 DOCX 副本" }).check();
  await page.getByRole("button", { name: "查看本页处理预览", exact: true }).click();
  await expect(page.getByRole("img", { name: "处理预览第 1 页" })).toBeVisible();
  await page.getByRole("button", { name: "保存复核", exact: true }).click();
  await expect(page.getByText("复核已保存", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "导出已选标记的处理副本", exact: true }).click();
  const button = page.getByRole("button", { name: "核验并下载 DOCX", exact: true }); await expect(button).toBeEnabled({ timeout: 30000 });
  const pending = page.waitForEvent("download"); await button.click(); const downloaded = await pending;
  expect(downloaded.suggestedFilename()).toBe("redacted.docx");
  const parts = await readZip(await readFile((await downloaded.path())!));
  expect([...parts.keys()].filter(n => n.startsWith("word/media/"))).toEqual(["word/media/redacted-1.png"]);
  expect(parts.get("word/document.xml")!.toString()).not.toContain("demo@example.com");
  await page.getByRole("region", { name: "页面预览" }).locator(".pagination").scrollIntoViewIfNeeded();
  await page.screenshot({ path: "test-results/docx-image-desktop.png", fullPage: true });
});
