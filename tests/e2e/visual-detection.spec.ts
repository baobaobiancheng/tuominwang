import { test, expect } from "./fixture.ts";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import sharp from "sharp";
test("automatic stamp proposals require confirmation and export cleared pixels", async ({ page }) => {
  test.setTimeout(90000);
  const image = await sharp(Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="500" height="700"><rect width="500" height="700" fill="white"/><circle cx="250" cy="500" r="55" fill="none" stroke="red" stroke-width="6"/></svg>')).png().toBuffer();
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/');
  await page.getByLabel('账号',{exact:true}).fill(process.env.E2E_USERNAME!);
  await page.getByLabel('密码',{exact:true}).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button',{name:'登录工作台'}).click();
  await page.locator('summary').click();
  await page.getByLabel('项目名称').fill('印章候选-'+randomUUID().slice(0,8));
  await page.getByRole('button',{name:'新建项目',exact:true}).click();
  await page.getByRole('button',{name:'导入材料',exact:true}).click();
  await page.getByLabel('选择文件',{exact:true}).setInputFiles({name:'合成印章.png',mimeType:'image/png',buffer:image});
  await page.getByRole('button',{name:'上传文件',exact:true}).click();
  await expect(page.getByText('已保存',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'返回材料列表',exact:true}).click();
  await page.getByRole('button',{name:/合成印章.png/}).click();
  await expect(page.getByRole('button',{name:'查找本页印章'})).toBeEnabled({timeout:30000});
  await page.getByRole('button',{name:'查找本页印章'}).click();
  await expect(page.getByRole('button',{name:'确认清除'})).toHaveCount(1);
  await expect(page.getByText('印章 · 区域 1',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'定位区域'}).click();
  await page.screenshot({path:'test-results/visual-candidates-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'确认清除'}).click();
  await expect(page.getByText('印章 · 区域 1',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'逐条复核',exact:true}).click();
  for(const decision of await page.getByLabel(/^标记 \d+ 处理决定$/).all()) await decision.selectOption('ignore');
  await page.getByRole('checkbox',{name:'生成清除选区像素的 PNG 副本'}).check();
  await page.getByRole('button',{name:'保存复核',exact:true}).click();
  await expect(page.getByText('复核已保存',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'导出已选标记的处理副本',exact:true}).click();
  const button=page.getByRole('button',{name:'核验并下载 PNG',exact:true});
  await expect(button).toBeEnabled({timeout:30000});
  const pending=page.waitForEvent('download');await button.click();const download=await pending;
  const {data,info}=await sharp(await readFile((await download.path())!)).removeAlpha().raw().toBuffer({resolveWithObject:true});
  const at=(500*info.width+250)*3;expect([...data.subarray(at,at+3)]).toEqual([0,0,0]);
});
