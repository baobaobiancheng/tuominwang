import { test, expect } from './fixture.ts';
import { createHash, randomUUID } from 'node:crypto';
import pg from 'pg';
import { MCP_PROTOCOL, taskUUID } from '../../packages/core/mcp-tools.ts';

test('delivered batch resumes through a new approval request and retains its original source and child selection', async ({page}, info) => {
  test.setTimeout(4 * 120_000 + 120_000);
  const dbUrl = new URL(process.env.MIGRATION_DATABASE_URL!);
  if (!dbUrl.pathname.startsWith('/tmw_test_')) throw new Error('ISOLATED_DATABASE_REQUIRED');
  const admin = new pg.Client({connectionString:dbUrl.href});
  await admin.connect();
  const origin = 'http://127.0.0.1:5178';
  const post = (path:string,data:unknown,headers:Record<string,string>={}) => page.request.post(path,{data,headers:{origin,...headers}});
  const ok = async (response:{status:()=>number;text:()=>Promise<string>;json:()=>Promise<any>}) => {expect(response.status(),await response.text()).toBe(200);return response.json();};
  let rpc=1;
  const client=async(name:string)=>{
    const initialized=await post('/api/mcp',{jsonrpc:'2.0',id:rpc++,method:'initialize',params:{protocolVersion:MCP_PROTOCOL,clientInfo:{name,version:'1'}}});
    expect(initialized.status()).toBe(200);
    const headers={'mcp-session-id':initialized.headers()['mcp-session-id'],'mcp-protocol-version':MCP_PROTOCOL};
    expect(headers['mcp-session-id']).toMatch(/^[a-f0-9]{64}$/);
    expect((await post('/api/mcp',{jsonrpc:'2.0',method:'notifications/initialized'},headers)).status()).toBe(202);
    return async(name:string,args:Record<string,unknown>)=>{
      const body=await ok(await post('/api/mcp',{jsonrpc:'2.0',id:rpc++,method:'tools/call',params:{name,arguments:args}},headers));
      return body.result as {isError:boolean;structuredContent:any};
    };
  };
  try {
    await page.goto('/');
    await page.getByLabel('账号',{exact:true}).fill(process.env.E2E_USERNAME!);
    await page.getByLabel('密码',{exact:true}).fill(process.env.E2E_PASSWORD!);
    await page.getByRole('button',{name:'登录工作台'}).click();
    await page.locator('.create-project summary').click();
    await page.getByLabel('项目名称',{exact:true}).fill(`MCP 批次接续-${randomUUID().slice(0,8)}`);
    const created=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/projects'&&r.request().method()==='POST');
    await page.getByRole('button',{name:'新建项目',exact:true}).click();
    const project=(await ok(await created)).id as string;
    const texts=['合成材料一：电话13800138000。','合成材料二：电话13900139000。'];
    const docs=[] as string[];
    for(const text of texts)docs.push((await ok(await post(`/api/projects/${project}/documents`,{text,requestId:randomUUID()}))).id);
    await expect.poll(async()=>{
      const views=await Promise.all(docs.map(id=>page.request.get(`/api/documents/${id}`).then(r=>r.json())));
      return views.map(d=>d.state==='review'&&d.job?.status==='succeeded');
    },{timeout:2*120_000,intervals:[1000,2000,5000]}).toEqual([true,true]);
    const original=await client('codex-batch-resume-edge');
    const started=await original('start_lawbot_redaction',{project_id:project,document_ids:docs,task_mode:'redact_only',masking_mode:'default_mask',batch_result_mode:'individual',output_formats:['original','md'],request_id:randomUUID()});
    expect(started.isError,JSON.stringify(started.structuredContent)).toBe(false);
    const parent=started.structuredContent.jobId as string,children=started.structuredContent.childJobIds as string[];
    expect(children).toHaveLength(2);
    expect(new Set(children).size).toBe(2);
    await page.goto(`/?collab=${parent}`);
    const panel=page.locator('section.panel').filter({has:page.getByRole('heading',{name:'AI 协作',exact:true})});
    const consent=panel.getByRole('group',{name:'授权给 codex'});
    await expect(consent).toBeVisible();
    await consent.getByRole('checkbox',{name:'允许读取本项目选定材料并脱敏'}).check();
    await consent.getByRole('checkbox',{name:'允许将经系统审定或人工复核的脱敏稿交给当前客户端'}).check();
    await consent.getByRole('checkbox',{name:'创建受保护的协作文件'}).check();
    await consent.getByRole('checkbox',{name:'授权后打开材料页'}).uncheck();
    const authorized=page.waitForResponse(r=>new URL(r.url()).pathname===`/api/ai-collab/tasks/${parent}/authorize`&&r.request().method()==='POST',{timeout:30000});
    await consent.getByRole('button',{name:'确认授权并自动处理'}).click();
    expect((await authorized).status()).toBe(200);
    // Both ordinary UI refresh and MCP polling may advance the same authorized batch.
    const [taskList, concurrentPoll]=await Promise.all([
      page.request.get('/api/ai-collab/tasks'),
      original('check_document_delivery',{job_id:parent,wait_seconds:0}),
    ]);
    expect(taskList.status(),await taskList.text()).toBe(200);
    expect(concurrentPoll.isError,JSON.stringify(concurrentPoll.structuredContent)).toBe(false);
    let ready:any;
    await expect.poll(async()=>{
      const response=await original('check_document_delivery',{job_id:parent,wait_seconds:0});
      expect(response.isError,JSON.stringify(response.structuredContent)).toBe(false);
      ready=response.structuredContent;
      return ready.documents?.map((item:any)=>item.status);
    },{timeout:3*120_000+30_000,intervals:[1000,2000,5000]}).toEqual(['sanitized_artifact_ready','sanitized_artifact_ready']);
    expect(ready.documents.map((item:any)=>item.jobId)).toEqual(children);
    expect(ready.documents.map((item:any)=>item.sanitizedArtifact.artifactId)).toEqual([expect.stringMatching(/^lba_[a-f0-9]{32}$/),expect.stringMatching(/^lba_[a-f0-9]{32}$/)]);
    const sourceBefore=await ok(await page.request.get(`/api/ai-collab/tasks/${parent}`));
    expect(sourceBefore.sources.map((item:{documentId:string})=>item.documentId)).toEqual(docs);
    const jobsBefore=(await admin.query('SELECT collab_task_id,kind,document_id FROM jobs WHERE collab_task_id = ANY($1::uuid[]) ORDER BY id',[children.map(taskUUID)])).rows;
    expect(jobsBefore.filter((item:{kind:string})=>item.kind==='detect')).toHaveLength(2);
    expect(jobsBefore.filter((item:{kind:string})=>item.kind==='export')).toHaveLength(2);
    const next=await client('claude-batch-resume-edge');
    const requested=await next('resume_lawbot_task',{job_id:parent});
    expect(requested.isError,JSON.stringify(requested.structuredContent)).toBe(false);
    const requestId=requested.structuredContent.jobId as string;
    expect(requestId).not.toBe(parent);
    expect(requested.structuredContent).toMatchObject({resumeSourceJobId:parent,resumeRequested:true,authorizationRequired:true});
    expect((await next('check_document_delivery',{job_id:parent,wait_seconds:0})).structuredContent.error).toBe('SESSION_AUTHORIZATION_REQUIRED');
    await page.goto(`/?collab=${requestId}`);
    const approval=panel.getByRole('group',{name:'接续任务授权给 claude'});
    await expect(approval).toBeVisible();
    await expect(panel.getByRole('group',{name:'已校验返回稿归档'})).toHaveCount(0);
    await expect(panel.getByRole('status').first()).toHaveText('申请接续已交付任务');
    await expect(panel.getByRole('combobox',{name:'协作任务'})).toHaveValue(requestId);
    const requestShot=info.outputPath('mcp-batch-resume-approval-request.png');
    await panel.screenshot({path:requestShot});
    await info.attach('mcp-batch-resume-approval-request',{path:requestShot,contentType:'image/png'});
    await approval.getByRole('checkbox',{name:'允许读取本项目选定材料并脱敏'}).check();
    await approval.getByRole('checkbox',{name:'允许将经系统审定或人工复核的脱敏稿交给当前客户端'}).check();
    await approval.getByRole('checkbox',{name:'创建受保护的协作文件'}).check();
    const approved=page.waitForResponse(r=>new URL(r.url()).pathname===`/api/ai-collab/tasks/${requestId}/authorize`&&r.request().method()==='POST',{timeout:30000});
    await approval.getByRole('button',{name:'确认授权并接续任务'}).click();
    const approvedResponse=await approved;
    expect(approvedResponse.status(),await approvedResponse.text()).toBe(200);
    expect((await approvedResponse.json()).jobId).toBe(parent);
    const requestAfter=await ok(await page.request.get(`/api/ai-collab/tasks/${requestId}`));
    expect(requestAfter.resumedJobId).toBe(parent);
    await expect(panel.getByRole('combobox',{name:'协作任务'})).toHaveValue(parent);
    const sourceAfter=await ok(await page.request.get(`/api/ai-collab/tasks/${parent}`));
    expect(sourceAfter.sources).toEqual(sourceBefore.sources);
    expect(sourceAfter.childJobIds).toEqual(children);
    const jobsAfter=(await admin.query('SELECT collab_task_id,kind,document_id FROM jobs WHERE collab_task_id = ANY($1::uuid[]) ORDER BY id',[children.map(taskUUID)])).rows;
    expect(jobsAfter).toEqual(jobsBefore);
    expect((await original('check_document_delivery',{job_id:parent,wait_seconds:0})).structuredContent.error).toBe('SESSION_AUTHORIZATION_REQUIRED');
    const alias=await next('check_document_delivery',{job_id:requestId,wait_seconds:0});
    expect(alias.isError,JSON.stringify(alias.structuredContent)).toBe(false);
    expect(alias.structuredContent.jobId).toBe(parent);
    expect(alias.structuredContent.documents.map((item:any)=>item.jobId)).toEqual(children);
    const selector=panel.getByRole('group',{name:'逐份任务'});
    await expect(selector).toBeVisible();
    await selector.getByRole('button',{name:'材料 2',exact:true}).click();
    await expect(selector.getByRole('button',{name:'材料 2 · 当前'})).toBeVisible();
    await expect(panel.getByRole('button',{name:'查看材料 2'})).toBeVisible();
    await expect(panel.getByRole('region',{name:'审定来源记录'})).toContainText('材料 2：');
    await expect(panel.getByRole('status').first()).toContainText('1 份材料');
    const childTask=await ok(await page.request.get(`/api/ai-collab/tasks/${children[1]}`));
    expect(childTask).toMatchObject({parentJobId:parent,sources:[expect.objectContaining({documentId:docs[1]})]});
    const selectedShot=info.outputPath('mcp-batch-original-child-selected.png');
    await panel.screenshot({path:selectedShot});
    await info.attach('mcp-batch-original-child-selected',{path:selectedShot,contentType:'image/png'});
    const chosen=ready.documents[1].sanitizedArtifact.artifactId as string;
    const received=await next('receive_sanitized_document',{job_id:requestId,artifact_id:chosen,output_format:'md'});
    expect(received.isError,JSON.stringify(received.structuredContent)).toBe(false);
    expect(received.structuredContent.jobId).toBe(children[1]);
    expect(received.structuredContent.artifactId).toBe(chosen);
    const bytes=Buffer.from(received.structuredContent.bytesBase64,'base64');
    expect(bytes.length).toBeGreaterThan(0);
    expect(createHash('sha256').update(bytes).digest('hex')).toBe(received.structuredContent.sha256);
    expect(bytes.toString('utf8')).not.toContain('13900139000');
    expect(bytes.toString('utf8')).not.toContain('13800138000');
    await selector.getByRole('button',{name:'材料 1',exact:true}).click();
    await expect(selector.getByRole('button',{name:'材料 1 · 当前'})).toBeVisible();
    await expect(panel.getByRole('button',{name:'查看材料 1'})).toBeVisible();
    await expect(panel.getByRole('region',{name:'审定来源记录'})).toContainText('材料 1：');
    await expect(panel.getByRole('status').first()).toContainText('1 份材料');
    await selector.getByRole('button',{name:'返回批次'}).click();
    await expect(panel.getByRole('status').first()).toContainText('2 份材料');
  } finally { await admin.end(); }
});
