test("known-entity scans bind the full text and draft to permissions/revisions; pending alias additions use normal snapshot validation", async () => {
  const tenant = randomUUID(), origin = process.env.APP_ORIGIN!, password = "synthetic-known-entity-password";
  async function account() {
    const username = "coverage-" + randomUUID();
    await admin.query("INSERT INTO users VALUES($1,$2,$3,$4)", [randomUUID(), tenant, username, passwordHash(password)]);
    const login = await app.inject({ method: "POST", url: "/api/login", headers: { origin }, payload: { username, password } });
    assert.equal(login.statusCode, 200, login.body);
    const cookie = String(login.headers["set-cookie"]).split(";")[0];
    return (method: any, url: string, payload?: any) => app.inject({ method, url, headers: { origin, cookie }, payload });
  }
  const req = await account(), other = await account();
  const project = (await req("POST", "/api/projects", { name: "已知实体检查" })).json().id;
  const text = "😀合成甲公司|合成甲公司|" + "x".repeat(40000) + "合成甲公司";
  const doc = (await req("POST", `/api/projects/${project}/documents`, { text, requestId: randomUUID() })).json().id, url = `/api/documents/${doc}`;
  await tick();
  const alias = (await req("POST", url + "/mappings", { revision: 0, start: 2, end: 7, kind: "机构", requestId: randomUUID() })).json();
  const marks = [{ start: 2, end: 7, kind: "机构", decision: "redact", replacement: alias }, { start: 8, end: 13, kind: "机构", decision: "ignore" }];
  assert.equal((await req("PUT", url + "/review", { revision: 0, marks })).statusCode, 200);
  const before = (await admin.query("SELECT content,content_hash,revision FROM documents WHERE id=$1", [doc])).rows[0];
  const scanned = await req("POST", url + "/known-entities", { revision: 1, marks });
  assert.equal(scanned.statusCode, 200, scanned.body);
  const result = scanned.json();
  assert.deepEqual(result.entities[0].matches.map((m: any) => m.status), ["marked", "retained", "missing"]);
  assert.equal(result.additions[0].start, text.length - 5); assert.equal(result.additions[0].decision, "pending");
  assert.deepEqual(result.additions[0].replacement, alias);
  assert.deepEqual((await admin.query("SELECT content,content_hash,revision FROM documents WHERE id=$1", [doc])).rows[0], before);
  assert.equal((await other("POST", url + "/known-entities", { revision: 1, marks })).statusCode, 404);
  const memberName = "coverage-member-" + randomUUID(), created = await req("POST", "/api/organization/members", { username: memberName, password });
  assert.equal(created.statusCode, 200, created.body);
  const memberId = created.json().id, login = await app.inject({ method: "POST", url: "/api/login", headers: { origin }, payload: { username: memberName, password } });
  const cookie = String(login.headers["set-cookie"]).split(";")[0], member = (method: any, path: string, payload?: any) => app.inject({ method, url: path, headers: { origin, cookie }, payload });
  const grant = await req("PUT", `/api/projects/${project}/members/${memberId}`, { revision: null, permissions: ["view_original"] }); assert.equal(grant.statusCode, 200, grant.body);
  const searchBody = { revision: 1, query: "合成甲公司", scope: "outside", spans: marks.map(({ start, end, decision }) => ({ start, end, decision })) };
  const scopedSearch = await member("POST", url + "/search", searchBody);
  assert.equal(scopedSearch.statusCode, 200, scopedSearch.body);
  assert.deepEqual(scopedSearch.json().matches.map((m: any) => m.start), [8, text.length - 5]);
  assert.equal((await other("POST", url + "/search", searchBody)).statusCode, 404);
  assert.equal((await member("POST", url + "/search", { ...searchBody, revision: 0 })).statusCode, 409);
  assert.equal((await member("POST", url + "/known-entities", { revision: 1, marks })).statusCode, 403);
  assert.equal((await req("PUT", `/api/projects/${project}/members/${memberId}`, { revision: grant.json().revision, permissions: ["view_original", "review"] })).statusCode, 200);
  assert.equal((await member("POST", url + "/known-entities", { revision: 1, marks })).statusCode, 200);
  const supplemented = [...marks, ...result.additions];
  assert.equal((await member("PUT", url + "/review", { revision: 1, marks: supplemented })).statusCode, 403);
  assert.equal((await req("PUT", url + "/review", { revision: 1, marks: supplemented })).statusCode, 200);
  const afterScan = (await req("POST", url + "/known-entities", { revision: 2, marks: supplemented })).json();
  assert.deepEqual(afterScan.additions, []);
  assert.equal((await req("POST", url + "/known-entities", { revision: 1, marks })).statusCode, 409);
  const after = (await admin.query("SELECT content,content_hash FROM documents WHERE id=$1", [doc])).rows[0];
  assert.equal(after.content, before.content); assert.equal(after.content_hash, before.content_hash);
  const snapshot = (await admin.query("SELECT marks FROM review_snapshots WHERE document_id=$1 AND revision=2", [doc])).rows[0].marks;
  assert.equal(snapshot[2].decision, "pending"); assert.deepEqual(snapshot[2].replacement, alias);
});
