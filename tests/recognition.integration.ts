test("encrypted project dictionary invalidates policy snapshots; reruns are version bound and evidence cannot be forged", async () => {
  const user = randomUUID(), tenant = randomUUID(), username = "recognition-" + randomUUID(), password = "synthetic-dictionary-password";
  await admin.query("INSERT INTO users VALUES($1,$2,$3,$4)", [user, tenant, username, passwordHash(password)]);
  const origin = process.env.APP_ORIGIN!;
  const login = await app.inject({ method: "POST", url: "/api/login", headers: { origin }, payload: { username, password } });
  const cookie = String(login.headers["set-cookie"]).split(";")[0];
  const req = (method: any, url: string, payload?: any) => app.inject({ method, url, headers: { origin, cookie }, payload });
  const project = (await req("POST", "/api/projects", { name: "词表验证" })).json().id;
  const doc = (await req("POST", `/api/projects/${project}/documents`, { text: "合成甲乙公司 联系13800138000", requestId: randomUUID() })).json().id;
  await tick();
  let view = (await req("GET", `/api/documents/${doc}`)).json();
  assert.equal(view.marks.length, 1);
  assert.equal((await req("PUT", `/api/documents/${doc}/review`, { revision: 0, marks: view.marks.map((m: any) => ({ ...m, decision: "redact" })) })).statusCode, 200);
  await req("POST", `/api/documents/${doc}/export`, { revision: 1 }); await tick();
  const link = (await req("POST", `/api/documents/${doc}/download-link`, { revision: 1 })).json();
  assert.ok(link.url);
  const entries = [{ value: "合成甲乙公司", kind: "机构" }];
  assert.equal((await req("PUT", `/api/projects/${project}/dictionary`, { revision: 0, entries })).statusCode, 200);
  assert.equal((await req("PUT", `/api/projects/${project}/dictionary`, { revision: 0, entries })).statusCode, 409);
  const workbook = await req("GET", `/api/projects/${project}/dictionary.xlsx?revision=1`);
  assert.equal(workbook.statusCode, 200);
  assert.deepEqual(await importDictionary(workbook.rawPayload), entries);
  assert.equal((await req("GET", `/api/projects/${project}/dictionary.xlsx?revision=0`)).statusCode, 409);
  const white = [{ value: "13800138000", kind: "手机号" as const, action: "exclude" as const }];
  const imported = await app.inject({ method: "POST", url: `/api/projects/${project}/dictionary/import?revision=1`, headers: { origin, cookie, "content-type": "application/octet-stream" }, payload: await exportDictionary(white) });
  assert.equal(imported.statusCode, 200); assert.deepEqual(imported.json().entries, white);
  // Import produces a draft, never overwrites policy or invalidates documents by itself.
  assert.deepEqual((await req("GET", `/api/projects/${project}/dictionary`)).json().entries, entries);
  const stored = (await admin.query("SELECT dictionary FROM projects WHERE id=$1", [project])).rows[0].dictionary;
  assert.ok(!stored.includes("合成甲乙公司"));
  assert.equal((await req("POST", `/api/documents/${doc}/download-link`, { revision: 1 })).statusCode, 409);
  assert.equal((await app.inject({ url: link.url })).statusCode, 200);
  view = (await req("GET", `/api/documents/${doc}`)).json();
  assert.equal(view.state, "outdated");
  assert.equal((await req("PUT", `/api/documents/${doc}/review`, { revision: view.revision, marks: [] })).json().error, "POLICY_CHANGED");
  assert.equal((await req("POST", `/api/documents/${doc}/recognize`, { revision: view.revision, ner: false })).statusCode, 200);
  assert.equal((await req("POST", `/api/documents/${doc}/recognize`, { revision: view.revision, ner: false })).statusCode, 409);
  await tick();
  view = (await req("GET", `/api/documents/${doc}`)).json();
  assert.deepEqual(view.marks.map((m: any) => m.kind), ["机构", "手机号"]);
  assert.ok(view.marks.every((m: any) => m.decision === "pending"));
  const fake = view.marks.map((m: any) => ({ ...m, decision: "ignore", sources: [{ layer: "ai", code: "forged" }] }));
  assert.equal((await req("PUT", `/api/documents/${doc}/review`, { revision: view.revision, marks: fake })).statusCode, 200);
  view = (await req("GET", `/api/documents/${doc}`)).json();
  assert.ok(view.marks.every((m: any) => m.sources[0].layer === "rules"));
  await admin.query("UPDATE documents SET recognition='{}' WHERE id=$1", [doc]);
  assert.equal((await req("POST", `/api/documents/${doc}/export`, { revision: view.revision })).json().error, "SNAPSHOT_MISMATCH");
  const otherId = randomUUID(), otherName = "other-" + randomUUID();
  await admin.query("INSERT INTO users VALUES($1,$2,$3,$4)", [otherId, tenant, otherName, passwordHash(password)]);
  const otherLogin = await app.inject({ method: "POST", url: "/api/login", headers: { origin }, payload: { username: otherName, password } });
  const otherCookie = String(otherLogin.headers["set-cookie"]).split(";")[0];
  assert.equal((await app.inject({ url: `/api/projects/${project}/dictionary`, headers: { cookie: otherCookie } })).statusCode, 404);
});
test("draft preview and search are owner/version bound; saved partial replacements produce the verified artifact", async () => {
  const tenant = randomUUID(), password = "synthetic-review-password", origin = process.env.APP_ORIGIN!;
  async function account() {
    const username = "review-" + randomUUID();
    await admin.query("INSERT INTO users VALUES($1,$2,$3,$4)", [randomUUID(), tenant, username, passwordHash(password)]);
    const login = await app.inject({ method: "POST", url: "/api/login", headers: { origin }, payload: { username, password } });
    const cookie = String(login.headers["set-cookie"]).split(";")[0];
    return (method: any, url: string, payload?: any) => app.inject({ method, url, headers: { origin, cookie }, payload });
  }
  const req = await account(), other = await account();
  const project = (await req("POST", "/api/projects", { name: "处理预览" })).json().id;
  const text = "😀客户甲 联系13800138000", doc = (await req("POST", `/api/projects/${project}/documents`, { text, requestId: randomUUID() })).json().id;
  await tick();
  const view = (await req("GET", `/api/documents/${doc}`)).json();
  const marks = view.marks.map((m: any) => ({ ...m, decision: "redact", replacement: { mode: "mask", prefix: 3, suffix: 4 } }));
  const previewBody = { revision: 0, marks };
  assert.equal((await req("POST", `/api/documents/${doc}/preview`, previewBody)).json().text, "😀客户甲 联系138***8000");
  assert.equal((await req("POST", `/api/documents/${doc}/search`, { revision: 0, query: "客户甲" })).json().matches[0].start, 2);
  const searchBody = { revision: 0, query: "客户甲", scope: "inside", spans: [{ start: 2, end: 5, decision: "pending", replacement: { mode: "alias", mappingId: "forged" }, sources: [{ code: "forged" }] }] };
  const scoped = await req("POST", `/api/documents/${doc}/search`, searchBody);
  assert.equal(scoped.statusCode, 200, scoped.body); assert.deepEqual(scoped.json().matches.map((m: any) => m.start), [2]);
  assert.equal((await req("POST", `/api/documents/${doc}/search`, { ...searchBody, spans: [{ start: 2, end: 5, decision: "ignore" }] })).json().matches.length, 0);
  assert.equal((await req("POST", `/api/documents/${doc}/search`, { ...searchBody, scope: "outside" })).json().matches.length, 0);
  assert.equal((await req("POST", `/api/documents/${doc}/search`, { ...searchBody, spans: [{ start: 2, end: 4, decision: "pending" }], scope: "outside" })).json().matches.length, 1);
  assert.equal((await req("POST", `/api/documents/${doc}/search`, { ...searchBody, spans: [{ start: 1, end: 5, decision: "pending" }] })).json().error, "INVALID_MARKS");
  assert.equal((await req("POST", `/api/documents/${doc}/search`, { ...searchBody, scope: "invalid" })).statusCode, 400);
  assert.deepEqual((await req("GET", `/api/documents/${doc}`)).json().marks, view.marks);
  assert.equal((await other("POST", `/api/documents/${doc}/preview`, previewBody)).statusCode, 404);
  assert.equal((await other("POST", `/api/documents/${doc}/search`, { revision: 0, query: "客户甲" })).statusCode, 404);
  assert.equal((await req("POST", `/api/documents/${doc}/preview`, { revision: 0, marks: [{ ...marks[0], replacement: { mode: "mask", prefix: 8, suffix: 3 } }] })).json().error, "INVALID_REPLACEMENT");
  assert.equal((await req("PUT", `/api/documents/${doc}/review`, previewBody)).statusCode, 200);
  assert.equal((await req("POST", `/api/documents/${doc}/preview`, previewBody)).statusCode, 409);
  assert.equal((await req("POST", `/api/documents/${doc}/search`, { revision: 0, query: "客户甲" })).statusCode, 409);
  assert.equal((await req("POST", `/api/documents/${doc}/export`, { revision: 1 })).statusCode, 200); await tick();
  const link = (await req("POST", `/api/documents/${doc}/download-link`, { revision: 1 })).json();
  assert.equal((await app.inject({ url: link.url })).body, "😀客户甲 联系138***8000");
  const stored = (await admin.query("SELECT marks FROM review_snapshots WHERE document_id=$1 AND revision=1", [doc])).rows[0].marks;
  assert.deepEqual(stored[0].replacement, { mode: "mask", prefix: 3, suffix: 4 });
});
