import pg from "pg";
import { readFile } from "node:fs/promises";
const c = new pg.Client({
  connectionString: process.env.MIGRATION_DATABASE_URL,
});
await c.connect();
try {
  await c.query("BEGIN");
  const role = await c.query("SELECT 1 FROM pg_roles WHERE rolname='tmw_app'");
  const pass = process.env.APP_DB_PASSWORD;
  if (!pass || !/^[a-f0-9]{48}$/.test(pass))
    throw new Error("APP_DB_PASSWORD must be generated by setup");
  if (!role.rowCount)
    await c.query(
      `CREATE ROLE tmw_app LOGIN PASSWORD '${pass}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE`,
    );
  await c.query(
    "CREATE TABLE IF NOT EXISTS schema_migrations(version text PRIMARY KEY)",
  );
  for (const version of ["001", "002", "003", "004", "005", "006", "007", "008", "009", "010", "011", "012", "013", "014", "015", "016", "017", "018", "019", "020", "021", "022", "023", "024", "025", "026", "027", "028", "029", "030", "031", "032", "033", "034", "035", "036", "037", "038", "039", "040"]) if (
    !(await c.query("SELECT 1 FROM schema_migrations WHERE version=$1", [version]))
      .rowCount
  ) {
    await c.query(
      await readFile(new URL(`./${version}.sql`, import.meta.url), "utf8"),
    );
    await c.query("INSERT INTO schema_migrations VALUES($1)", [version]);
  }
  await migrateLegacyPageReviewMetadata(c);
  await c.query("COMMIT");
  console.log("数据库迁移完成");
} catch (e) {
  await c.query("ROLLBACK");
  throw e;
} finally {
  await c.end();
}
