import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { readFile, writeFile, mkdtemp, mkdir, cp, rm } from "node:fs/promises";
import { resolve, join } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const bend = resolve(process.env.BEND_ROOT ?? resolve(root, "../../bend"));
const cli = join(bend, "bend2/main.ts");
const env = { ...process.env, BEND_NO_TELEMETRY: "1" };
const mode = process.argv[2] ?? "check";
if (!["check", "build", "mutations"].includes(mode)) throw new Error("Expected check, build or mutations");
const lock = JSON.parse(await readFile(new URL("./bend-lock.json", import.meta.url), "utf8"));
for (const [path, expected] of Object.entries(lock.files)) {
  const bytes = await readFile(join(bend, path)).catch(() => { throw new Error("找不到已锁定的 Bend 源码，请设置 BEND_ROOT。不会自动安装或跳过证明。"); });
  if (createHash("sha256").update(bytes).digest("hex") !== expected) throw new Error(`Bend 源码版本不一致：${path}；请先评审版本变化。`);
}
function run(args: string[], cwd = root) {
  const result = spawnSync("bun", args, { cwd, env, encoding: "utf8", timeout: 30000, maxBuffer: 8 * 1024 * 1024 });
  if (result.error) throw result.error;
  return result;
}
function proof(cwd = root) {
  return run([cli, "PROOF.bend", "--check-only"], cwd);
}
const checked = proof();
if (checked.status !== 0 || !checked.stdout.includes("All terms check.")) throw new Error(checked.stderr || checked.stdout || "Bend proof failed");

if (mode === "mutations") {
  const temp = await mkdtemp(join(tmpdir(), "tmw-bend-mutations-"));
  try {
    await mkdir(join(temp, "packages/core"), { recursive: true });
    await cp(join(root, "LAWS.bend"), join(temp, "LAWS.bend"));
    await cp(join(root, "PROOF.bend"), join(temp, "PROOF.bend"));
    const original = await readFile(join(root, "packages/core/export-policy.bend"), "utf8");
    const mutations: [string, string[]][] = [
      ["ready && (version && (covered && (reviewed && snapshot)))", ["True{}", "False{}", "version && (covered && (reviewed && snapshot))", "ready && (covered && (reviewed && snapshot))", "ready && (version && (reviewed && snapshot))", "ready && (version && (covered && snapshot))", "ready && (version && (covered && reviewed))"]],
      ["authorized && (current && (known && unambiguous))", ["True{}", "False{}", "current && (known && unambiguous)", "authorized && (known && unambiguous)", "authorized && (current && unambiguous)", "authorized && (current && known)"]],
    ];
    for (const [expression, alternatives] of mutations) {
      if (!original.includes(expression)) throw new Error("Update mutation cases for changed implementation; do not weaken laws");
      for (const bad of alternatives) {
      await writeFile(join(temp, "packages/core/export-policy.bend"), original.replace(expression, bad));
      // First establish this is well-typed code, not merely a syntax-error rejection.
      if (run([cli, "packages/core/export-policy.bend", "--check-only"], temp).status !== 0) throw new Error("Invalid mutation");
      const rejected = proof(temp);
      if (rejected.status === 0) throw new Error(`Proof gate accepted unsafe mutation: ${bad}`);
      }
    }
    console.log("Bend: all 13 valid-but-incorrect mutations rejected.");
  } finally { await rm(temp, { recursive: true }); }
} else {
  // Use Bend's own module loader/compiler. Do not hand-maintain a TS duplicate of the policy.
  const source = pathToFileURL(join(root, "packages/core/export-policy.bend")).href;
  const compiler = run(["-e", `const {load} = await import(${JSON.stringify(pathToFileURL(cli).href)}); const r = await load(${JSON.stringify(source)}, {}, () => {throw new Error("Unexpected import")}); process.stdout.write(r.source);`]);
  if (compiler.status !== 0 || !compiler.stdout.includes("export default")) throw new Error(compiler.stderr || "Bend compilation failed");
  const output = `// Generated by Bend ${lock.version} (${lock.commit}). Do not edit.\n// Bend-generated runtime: Apache-2.0; see 文档/Bend方法与验证边界.md.\n` + compiler.stdout;
  const target = join(root, "packages/core/export-policy.generated.js");
  const types = "// Generated by scripts/bend.ts. Do not edit.\ndeclare const policy: {\n  eligible(ready: boolean, version: boolean, covered: boolean, reviewed: boolean, snapshot: boolean): boolean;\n  restoreAllowed(authorized: boolean, current: boolean, known: boolean, unambiguous: boolean): boolean;\n};\nexport default policy;\n";
  const declarations = join(root, "packages/core/export-policy.generated.d.ts");
  if (mode === "build") { await writeFile(target, output); await writeFile(declarations, types); }
  else if (await readFile(target, "utf8") !== output || await readFile(declarations, "utf8") !== types) throw new Error("Bend 编译产物与已证明源码不一致。运行 pnpm bend:build 后重新检查。");
  console.log(`Bend: 11 laws checked; runtime artifact ${mode === "build" ? "generated" : "matches proven source"}.`);
}
